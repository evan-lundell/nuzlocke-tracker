export const NICKNAME_THEMES = Object.keys(THEME_NAMES);

/**
 * Picks up to `count` names: from the theme if one is given, otherwise from
 * the Pokémon's types. Skips names already taken or over the game's limit.
 */
export function pickListNicknames({
	types,
	theme,
	takenNicknames,
	maxLength,
	count = 5,
	random = Math.random,
}: {
	types: string[];
	theme?: string;
	takenNicknames: string[];
	maxLength: number;
	count?: number;
	random?: () => number;
}) {
	const pool =
		(theme && THEME_NAMES[theme]) || types.flatMap((t) => TYPE_NAMES[t] ?? []);
	const taken = new Set(takenNicknames.map((n) => n.trim().toLowerCase()));
	const candidates = [...new Set(pool)].filter(
		(n) => [...n].length <= maxLength && !taken.has(n.toLowerCase()),
	);
	// Fisher-Yates shuffle, then take the first few
	for (let i = candidates.length - 1; i > 0; i--) {
		const j = Math.floor(random() * (i + 1));
		[candidates[i], candidates[j]] = [candidates[j], candidates[i]];
	}
	return candidates.slice(0, count);
}
